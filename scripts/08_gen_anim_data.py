# Goblin enemy - writes roblox/ReplicatedStorage/Goblin/GoblinAnimData.lua from docs/animation_manifest.json.
# Plain Python 3:  python3 08_gen_anim_data.py   (re-run whenever 03_animations.py changes the manifest)
import json, os

ROOT = os.environ.get("GOBLIN_ROOT", os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "docs", "animation_manifest.json")
DST = os.path.join(ROOT, "roblox", "ReplicatedStorage", "Goblin", "GoblinAnimData.lua")


def main():
    anims = json.load(open(SRC))["animations"]
    lines = ["-- GENERATED by scripts/08_gen_anim_data.py from docs/animation_manifest.json. Do not edit by hand.",
             "-- Per animation: length (s), looped, priority and timed events {name, seconds} in play order.",
             "return {"]
    for name in sorted(anims):
        a = anims[name]
        ev = ", ".join('{ "%s", %s }' % (e, t) for e, t in sorted(a["events"].items(), key=lambda kv: kv[1]))
        lines.append('\t%s = { length = %s, looped = %s, priority = "%s", events = { %s } },'
                     % (name, a["duration"], str(a["loop"]).lower(), a["priority"], ev))
    lines.append("}")
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", DST, len(anims), "animations")


if __name__ == "__main__":
    main()
