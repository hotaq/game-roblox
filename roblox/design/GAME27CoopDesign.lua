ข้อเสนอที่แนะนำ
ทีม 1–4 คนเริ่มพร้อมกัน อยู่ใน arena เดียว ใช้นาฬิการอบเดียวกัน
ใครเก็บ gem ก็ให้ XP เต็มจำนวนแก่สมาชิกที่ยังมีสิทธิ์ทุกคน แต่เลือกการ์ด/build ของตัวเอง
ล็อกสมาชิกตอนเริ่ม คนมาทีหลังรอรอบถัดไป คนตายไม่เกิดกลับมาในรอบเดิม
เมื่อถึงเวลาเป้าหมาย สมาชิกที่ยังมีชีวิตและอยู่ใน arena ชนะพร้อมกัน
ไม่มีเงินถาวร ของซื้อขาย คะแนนจัดอันดับ หรือระบบชุบชีวิตในต้นแบบแรก

พฤติกรรมปัจจุบันที่ตรวจจาก source (ไม่ใช่ข้อเสนอ)
- runs แยกตาม Player แต่มี arena และฝูงเดียว; pad เปลี่ยน arena ได้เมื่อไม่มี run
- step เริ่ม run ให้คนมีชีวิตที่เข้าขอบ arena จึงยังเข้าเกมกลางรอบได้
- kill ให้เครดิต kill แก่ผู้ทำความเสียหายจนตาย แล้วสร้าง gem หนึ่งชิ้น
- pickup ลบ gem และให้ GemXP=1 แก่ target คนแรกในลูปที่อยู่ในระยะเก็บ
  ไม่ได้เลือกคนที่ใกล้ที่สุด และไม่จำเป็นต้องเป็นคนฆ่า; คนอื่นไม่ได้ XP ของ gem นั้น
- level, xp, weapons, passives, rerolls, damage แยกรายคน
- ฝูงสเกลตาม run ที่เก่าที่สุด; ไม่มี party-size multiplier โดยตรง
- ใครเลือกการ์ดก็หยุด step ทั้งเกม แต่ run.start ชดเชยเฉพาะผู้เลือกการ์ด
- ตายจบเฉพาะ run ของคนนั้น; ออกจากเกมลบ runs[player]; ไม่มีผล victory อยู่แล้ว
  การลบ runs อย่างเดียวไม่ใช่หลักฐานว่าทุก projectile/reference ถูกเก็บครบ (GAME-25)

ตารางเปรียบเทียบ XP / reward ownership
ทางเลือก | จุดแข็ง | ปัญหา/ต้นทุน | ข้อสรุปรุ่นแรก
คนเก็บได้คนเดียว | ใกล้กับระบบเดิมและเข้าใจง่าย | แย่ง gem; Magnet เร็วกว่าเพื่อนยิ่งทิ้งห่าง | ไม่เลือก
ทุกคนที่ร่วมทีมได้เต็ม | ร่วมมือเก็บ ไม่แย่ง; แยกเดินได้ | คนไม่ช่วยอาจถูกแบก; XP เร็วขึ้นถ้าฆ่าเร็วขึ้น | เลือกสำหรับต้นแบบ
เฉพาะคนใกล้/ผู้ช่วยตี | จำกัดการรับจากไกลและให้เครดิตการช่วย | เกณฑ์ระยะ/เวลา/assist ซับซ้อน; คนล่อฝูงอาจไม่ได้ | เก็บเป็นทางเลือกภายหลัง
เกณฑ์ nearby ตัวอย่างที่พิจารณาแต่ไม่เลือก: อยู่ในระยะ 60 studs ตอนศัตรูตาย
หรือทำ damage ใน 10 วินาทีก่อนตาย; ต้องป้องกันตีเบา ๆ แล้วหนีและรองรับ slot reuse
ค่าระยะ/เวลาเหล่านี้เป็นตัวอย่างเปรียบเทียบ ไม่ใช่ค่าที่ผ่านการวัดหรือควรแอบนำไปใช้

ตารางกติกาที่เลือก (ทั้งหมดเป็น proposal)
เรื่อง | กติกา | เหตุผล
XP ต่อ gem | ผู้มีสิทธิ์แต่ละคนได้ 1 XP ไม่หารจำนวนคน | ไม่ลงโทษคนที่ให้เพื่อนเก็บ
เลือกอัปเกรด | level/XP/loadout แยกคน; การ์ดและ 2 rerolls แยกคน | ทุกคนกำหนด build เอง
kill/damage | kill เฉพาะผู้ปิดงาน; damage ตามที่ทำจริง; team kill นับครั้งเดียว | สถิติไม่กำหนดส่วนแบ่ง XP
Magnet | เพิ่มระยะเก็บของเจ้าของตามเดิม; XP กระจายให้ทีม | เป็นประโยชน์ต่อทีมโดยไม่แย่ง XP
คนไกลกัน | รับ XP เท่ากันถ้ายังมีสิทธิ์ แม้อยู่คนละฝั่ง Map1 | ไม่บังคับยืนติดกันเพื่อเก็บรางวัล
เลเวลต่างกัน | เพิ่ม XP เท่ากัน เข้าเกณฑ์ level ของแต่ละคน ไม่ปรับ level ให้เท่าทันที | รักษาความหมายของ XP และ loadout
ชนะ | shared encounter time ถึง 480 วินาที; ผู้รอดและอยู่ใน arena ชนะพร้อมกัน | ไม่มีคนหนึ่งทำให้เพื่อนเสียรอบก่อนเวลา
ตาย | defeated ทันที; ไม่รับ XP/ชัยชนะที่เกิดหลังตาย | ไม่สามารถตายแล้วกลับมารับของรอบเดิม
ออก/หลุด | abandoned; กลับเข้ามาถือเป็นผู้รอรอบหน้า | ไม่ต้องสร้างระบบ reconnect restoration รุ่นแรก
รางวัลปลายรอบ | outcome + สถิติเท่านั้น | ยังไม่ผูกการทดลองกับเศรษฐกิจถาวร

นิยามสมาชิกและวงจรรอบ
1. Waiting: เสนอคิวผ่าน pad เดิม สูงสุด 4 คนต่อรอบทดสอบ
   คนแรกเลือก arena แล้วเปิด countdown 10 วินาที; คนถัดไปเห็น arena ที่เลือกและเวลารอ
   เปลี่ยน map ระหว่าง countdown ไม่ได้; ผู้เล่นยกเลิกคิวได้จนถึงจุดล็อกสมาชิก
   ถ้าคิวว่างให้ยกเลิก countdown; ถ้ามีเกิน 4 ให้ผู้มาทีหลังรอ ไม่แทรกแทนคนก่อน
   เมื่อหมดเวลา ล็อกเฉพาะคนที่ยังเชื่อมต่อ/พร้อมเล่นตามลำดับเข้า เลื่อนคนรอมาแทนช่องว่างได้ก่อนล็อกเท่านั้น
2. Active: สร้าง encounterId และ roster ที่ล็อกแล้ว; เริ่มทุกคน Lv1/sword Lv1/XP0
   คนที่โหลดตัวละครไม่สำเร็จต้องถูกตัดออกก่อนเริ่ม; n0 นับสมาชิกที่เริ่มได้จริง
   ถ้าไม่มีใครพร้อมกลับ Waiting; ไม่เพิ่มคนหลัง combat clock เริ่มแล้ว
3. Late join: อยู่ camp และเห็น “RUN IN PROGRESS — NEXT RUN”; ไม่ให้ย้ายเข้าฝูงที่กำลังเล่น
   ไม่สะสม XP/เวลาและไม่มี catch-up package; มีสิทธิ์จองรอบถัดไป
   ยอมรับข้อเสียว่าอาจต้องรอนานถึงหนึ่งรอบ ต้องวัดว่าผู้เล่นเลิกรอกี่คน
4. Dead/abandoned: จบผลเฉพาะคนนั้นและย้ายออก; เพื่อนที่ยังเล่นดำเนินต่อ
   Play Again เข้าคิวรอบหน้า ไม่เกิดในรอบเดิม; Lobby ออกจากคิวและอยู่ camp
5. Terminal: ถ้าทุกคนตาย/ออก ให้รอบจบทันที; ถ้าครบเวลาให้ตัดสินผลสมาชิกที่เหลือ
   ปิด damage/XP/cards ก่อนเคลียร์ฝูงและย้ายคนออก; การเคลียร์ห้ามสร้าง gem/kill reward
   หลัง cleanup เสร็จจึงเปิด countdown รอบใหม่สำหรับคนที่เลือกเข้าคิวไว้
คิวนี้คือข้อเสนอ flow ไม่ใช่ UI ที่สร้างแล้ว; ต้นแบบอาจกำหนด roster ของผู้ทดสอบไว้ก่อน
แต่การเปิดให้ผู้เล่นจริงต้องมีข้อความรอ/ยกเลิกที่ชัดเจน ไม่ปล่อย pad ดูเหมือนไม่ทำงาน

นาฬิการอบ การเลือกการ์ด และขอบ arena
- ใช้ shared active-combat clock สำหรับ timeline, growth และ victory; ไม่ใช้ max(now-run.start)
- ในรุ่นที่ยังหยุดฝูงทั้งเกม ให้หยุด clock ร่วมด้วยตลอดช่วงที่มีการ์ดค้างอย่างน้อยหนึ่งคน
  การ์ดหลายคนซ้อนกันให้นับช่วง pause รวมครั้งเดียว ไม่บวกเวลารอซ้ำตามจำนวนคน
- GAME-11 per-player pause ไม่อยู่ในงานนี้ และ implementation ที่ถูกย้อนห้ามนำกลับมาเอง
- ข้อเสนอป้องกันคนค้างการ์ด: deadline 20 วินาที wall-clock ต่อการ์ดที่ต้องเลือก
  เมื่อหมดให้เซิร์ฟเวอร์เลือกใบแรกที่เสนอและยัง valid; reroll ไม่ต่อ deadline
  ถ้าเลือกและ timeout มาพร้อมกัน ให้ cardOfferId เดียวตัดสินได้ครั้งเดียว
  ถ้ามีหลาย level ค้าง เปิด offer ใหม่ทีละอันพร้อม deadline ของอันนั้น; ต้องวัดเวลารอรวม
  การหมดเวลาจะเลือกให้อัตโนมัติต้องบอกในหน้าการ์ด เป็นข้อเสนอใหม่ที่ยังไม่ได้ implement
- คนออกขอบหยุดรับ XP ทันที; ถ้าไม่กลับใน 5 วินาที wall-clock ให้ abandoned ตาม GAME-26
  clock ของทีมไม่หยุดตามคนออกขอบ; คนใน arena เล่นต่อได้
  เมื่ออยู่ข้างนอกห้ามทำ damage/เก็บของจากนอกสนาม; ป้องกันหลบขอบรอชนะ
  ถ้าครบเวลาเป้าหมายขณะยังอยู่นอกขอบ ให้คนนั้น abandoned แม้ grace ยังเหลือ
- เมื่อ clock ถึงเส้นชัย ให้ตัดสิน death/leave ของ tick นั้นก่อน victory ตาม GAME-26
  ผู้ตายใน tick นั้นเป็น defeated; ผู้หลุดก่อน terminal commit เป็น abandoned
  คนที่ terminal commit เป็น victory แล้วหลุดภายหลังไม่เปลี่ยนผลย้อนหลัง แต่ไม่มีของส่งซ้ำ

นิยามผู้มีสิทธิ์รับ XP / reward
เป็นสมาชิก roster ของ encounter เดียวกัน, connected, state=active, มีชีวิต,
และอยู่ในขอบ arena ณ ตอนเซิร์ฟเวอร์ตัดสิน event; ไม่มีระยะใกล้ผู้เก็บหรือ kill requirement
“active” เป็นสถานะรอบ ไม่ได้อ้างว่ามีระบบตรวจ AFK ที่แม่นยำ
คนดู/คนใน camp/คนตาย/ผู้รอ/คนหลุดไม่มีสิทธิ์; ผู้เก็บต้องผ่านเงื่อนไขเดียวกัน
gem ของศัตรูหนึ่งตัวถูก consume ได้ครั้งเดียวก่อนกระจาย XP ไปยังรายชื่อผู้มีสิทธิ์
เลือกการ์ดค้างไม่ตัดสมาชิกออก แต่ตอน global pause ไม่มีการเก็บ gem ใหม่จน simulation เดินต่อ
XP เป็นค่ารายคน; รายชื่อ snapshot ไม่เปลี่ยนเพราะสมาชิกคนหนึ่ง level up ระหว่างแจก
HUD ควรแยก “XP RECEIVED” จากจำนวน gem ที่ตัวเองเก็บจริง เพื่อไม่อ้างว่าใครเก็บของแทนกัน
elite/optional objective ใน GAME-28/29 หากให้รางวัลทีม ให้ใช้ event เดียวและ eligibility
ชุดนี้ตอนสำเร็จ ไม่ให้ last-hit แย่งรางวัล; ชนิด/ปริมาณของรางวัลยังเป็นงานของ prototype นั้น

ความยากตามจำนวนผู้เล่น — สมมติฐานเริ่มต้นที่วัดได้
ใช้จำนวนฝูงตามเวลาเดิม B(t)=min(700,floor(25+45*t/60)); ไม่คูณจำนวนศัตรูตามทีม
HP ของตัวเกิดใหม่ = 30*(1+0.4*t/60)*M, M=1+0.5*(n0-1)
ทีมเริ่มต้น n0 | ตัวคูณ HP | เป้าหมายฝูงนาที 8 | HP ตัวเกิดใหม่นาที 8
1              | 1.0       | 385               | 126
2              | 1.5       | 385               | 189
3              | 2.0       | 385               | 252
4              | 2.5       | 385               | 315
Damage/ความเร็ว/จังหวะโจมตีศัตรูคงเดิมในต้นแบบนี้ เพื่อไม่ปรับหลายแกนพร้อมกัน
ล็อก n0 ตลอดรอบ; death/disconnect ไม่ heal ตัวที่มีอยู่ ไม่ลด HP ทั้งฝูงทันที
ข้อเสียที่ยอมรับสำหรับรุ่นแรก: เหลือคนเดียวจากทีม 4 คนจะยากขึ้นมาก อาจต้องเริ่มรอบใหม่
ถ้า playtest พบว่าการหลุดทำให้เกมหมดสนุก ให้ทดลองลด HP ของตัวเกิดใหม่หลังสมาชิกออก
เป็นทางเลือกแยก โดยไม่เติมเลือด/รีเซ็ตศัตรูเก่า; อย่าเพิ่มระบบนี้โดยไม่มีเหตุผลจากการเล่น
สูตรนี้จงใจทำให้ทีมช่วยกันได้เปรียบกว่าสเกล HP แบบ n0 เท่า ไม่รับประกัน XP/min คงเดิม
XP เต็มต่อคนร่วมกับการฆ่าเร็วขึ้นอาจเร่งทุกคน ต้องวัด progression ตาม GAME-26
ตัวเลขข้างต้นเป็นการคำนวณ ไม่ใช่ผลทดสอบความสนุกหรือคำรับรอง performance

ตัวอย่าง 2 คน: เก็บร่วม / ต่างเลเวล / อยู่ไกล
A และ B เริ่มพร้อมกัน; A ฆ่าและเก็บ gem G: team kills +1, A kills +1,
A XP +1 และ B XP +1; B ไม่ได้ kill เพิ่ม การส่งแจ้งเก็บ G ซ้ำให้ XP เพิ่มไม่ได้
ถ้า A/B อยู่ห่างกัน 160 studs แต่ยังอยู่ Map1 และ active ทั้งคู่ ผล XP เหมือนเดิม
ใครออกขอบ ณ ตอนเก็บจะไม่ได้ XP แม้กลับใน grace ทัน ทำให้ XP ต่างกันได้
ตัวอย่าง fixture ตรวจต่างเลเวล (ไม่อนุญาตนำเลเวลข้ามรอบ): A Lv2 มี XP6/7,
B Lv4 มี XP12/13; เก็บหนึ่ง gem -> A Lv3 XP0/10, B Lv5 XP0/17
แต่ละคนได้หนึ่งการ์ด เลือกอิสระ; ไม่ดึง B ลง Lv3 หรือเพิ่ม A เป็น Lv5
ถ้า A ตายที่ 6:00 ผล A=defeated; B ไปต่อด้วย HP multiplier 1.5
ถ้า B รอดถึง 8:00 B=victory; A ยัง defeated ไม่กลายเป็นชนะเพราะเพื่อนชนะ

ตัวอย่าง 4 คน: แยกกลุ่ม / หลุดระหว่างรางวัล / late join
A/B อยู่ฝั่งเหนือ C/D อยู่ฝั่งใต้; ทั้งสี่อยู่ใน arena และ active
A เก็บ G1: ทั้งสี่ได้คนละ 1 XP รวม XP ที่แจก 4 หน่วย ไม่ใช่คนละ 0.25
C เก็บ G2 ใน tick เดียวกัน: ทั้งสี่ได้อีกคนละ 1 รวมทั้งสอง gem คนละ 2
G1/G2 เป็นคนละ event แม้อยู่ตำแหน่งเดียวกัน; การซ้ำของ G1 ไม่เพิ่มครั้งที่สอง
D หลุดก่อน commit ของ G3: snapshot ผู้มีสิทธิ์คือ A/B/C ได้คนละ 1; D ได้ 0
ไม่มีการแบ่ง XP ส่วนของ D มาเพิ่มให้ A/B/C; ตัวคูณ HP ยัง 2.5
ถ้า D หลุดหลัง commit: G3 เคยถูกนับให้ D แล้ว แต่ run D จบ abandoned
กลับเข้ามาไม่คืน run/XP และไม่ replay G3; ไม่ย้อน XP ของ A/B/C
E เข้ามาที่ 7:50: อยู่คิวใน camp ได้ 0 XP จากรอบนี้ ไม่มี victory ตอน 8:00
เมื่อ A/B/C รอดครบเวลา ทั้งสาม victory; D abandoned; E เริ่มรอบใหม่ได้หลัง cleanup
คนใดคนหนึ่งกด Play Again ก่อนเพื่อนจบ ต้องไม่เปลี่ยน arena หรือ restart encounter ของเพื่อน

การกันรับซ้ำและลำดับ event ที่ต้นแบบต้องพิสูจน์
- ใช้ encounterId + reward sequence สำหรับ event; memberRunId/offerId สำหรับสิทธิ์รายคน
  อย่าใช้ slot ศัตรูหรือ gem u16 ที่วนกลับเป็นตัวระบุสิทธิ์ถาวรโดยลำพัง
- เซิร์ฟเวอร์ตัดสิน membership/death ที่ทราบใน tick -> pickup/reward -> victory
  critical commit ไม่ yield: consume event, snapshot eligibility, เพิ่ม XP ครั้งเดียวต่อคน
  event เก่าของรอบก่อนและ callback ของตัวละครเก่าห้ามเปลี่ยนรอบใหม่
- UI notification/ภาพ gem หายเป็นผลของ commit ไม่ใช่หลักฐานให้ client ขอ XP เอง
- death/leave ยกเลิก projectile ownership และ pending cards ของ run นั้น;
  อย่าส่งรางวัลจาก shot ที่ยังถือ reference ไปยัง run ที่จบแล้ว
- ถ้าทุกคนออก ข้ามการแจกและปิดรอบ/clear event ledger หลังยกเลิกงานค้าง
  ไม่จำเป็นต้องเก็บ ledger ข้ามเซิร์ฟเวอร์ เพราะไม่มี persistent rewards ในขอบเขตนี้
เป็นข้อกำหนดตรวจในงาน implementation ภายหลัง ไม่ใช่ระบบที่สร้างแล้วในเอกสารนี้

AFK และการใช้ช่องโหว่: สิ่งที่ป้องกันได้และข้อจำกัดที่ยอมรับ
camp/late join รอรับของ: กันด้วย roster และ in-arena eligibility
แย่ง last hit/ใช้ Magnet ดูดของเพื่อน: XP ร่วมลดแรงจูงใจ; kill เป็นสถิติเท่านั้น
หลุดแล้วเข้าใหม่รับซ้ำ/ลดความยาก: ไม่คืน run, ไม่ replay event, ล็อก n0
ค้างหน้าการ์ดแช่ทั้งทีม: เสนอ deadline ที่ไม่ยืดด้วย reroll; ยังต้องวัด pause ต่อรอบ
AFK ใน arena: ยังถูกเพื่อนแบกได้ เพราะอาวุธยิงเอง การนับ damage ไม่พิสูจน์การควบคุม
ไม่ใช้ mouse/keyboard activity หรือการยืนนิ่งเพียงอย่างเดียวตัด XP โดยเดา
ต้นแบบส่วนตัวบันทึกช่วงนิ่งและการรับ XP; หากยืนเฉย ๆ รอดบ่อย ต้องแก้ safe spot/
แรงกดดันหรือทบทวนสิทธิ์ก่อนให้รางวัลถาวร; ยังไม่อ้างว่าแก้ AFK สำเร็จ
ผู้เล่นออกเพราะเน็ตหลุดเสียรอบ: เป็นข้อเสียจริงของ no-reconnect รุ่นแรก ต้องสื่อสาร
และวัดจำนวนครั้งก่อนเลือกว่าจะลงทุนทำ reconnect restoration หรือ revive

