GAME-26 — เป้าหมายรอบเกม / Run length, milestones and victory
สถานะ: ข้อเสนอสำหรับทดลองเล่น ไม่ใช่กติกาที่เปิดใช้แล้ว
วันที่: 2026-10-27 | ตรวจโค้ดที่ main 3774b09

ข้อเสนอหลัก
ให้รอบแรกมีเป้าหมาย “อยู่รอด 8 นาที” โดยนับเวลาเล่นจริงที่ระบบต่อสู้เดินอยู่
นาทีสุดท้ายเป็นช่วงกดดันสูงสุด แล้วจบรอบอย่างชัดเจนเมื่อรอดครบเวลา
ใช้ศัตรู อาวุธ และพื้นที่เดิมก่อน เพื่อพิสูจน์ว่าการเลือกอัปเกรดและหลบฝูงสนุกพอ
ยังไม่ต้องมีบอส ไอเทมถาวร แผนที่ใหม่ หรืองานภาพเพิ่มเพื่อจบรอบ

เหตุผลที่ควรทำตอนนี้
เป้าหมายจบรอบกำหนดว่าควรได้อัปเกรดกี่ครั้ง เมื่อไรต้องเพิ่มแรงกดดัน และ Evolve
ควรมีเวลาให้ใช้แค่ไหน หากยังไม่กำหนดสิ่งนี้ การเพิ่มอาวุธ/elite/ภารกิจอาจต้องแก้ซ้ำ
GAME-25 ไม่จำเป็นต้องรอเกมเสร็จทั้งหมด แต่การทดสอบ lifecycle แบบยาวควรทำหลัง
start/end/restart/arena rules รุ่นแรกนิ่ง หรือทำทันทีหากพบอาการของค้างที่ทำซ้ำได้

สิ่งที่มีอยู่จริงจากโค้ด (แยกจากข้อเสนอ)
- เข้า arena แล้ว startRun; เริ่มด้วย sword Lv1, ตัวผู้เล่น Lv1, XP 0
- มี sword/fire/ring และ passives might/area/haste/magnet/force; ยังไม่มี Evolve
- เลือกได้ 4 ช่องอาวุธ / 4 ช่อง passive; อาวุธที่มีอยู่และ passive สูงสุด Lv5
- เลเวลแรกใช้ 5 XP; ครั้งถัดไป round(previous * 1.22 + 1); ไม่รับประกันเวลาเลเวลอัป
- เมื่อใครเลือกการ์ด step() หยุดทั้งฝูง แต่ชดเชย run.start เฉพาะคนเลือกการ์ด
  นาฬิกาของเพื่อนจึงไม่ใช่เวลาที่ฝูงทำงานจริง ห้ามใช้ตรง ๆ เป็น shared victory clock
- endRun ถูกเรียกจาก Humanoid.Died; RunOver ส่ง time/kills/level/damage ไม่มี outcome
- หน้าผลปัจจุบันเขียน GREAT RUN!; ยังไม่แยกชัยชนะกับความตาย
- จำนวนเป้าหมายฝูง = min(700, floor(25 + 45 * longestRunMinutes))
  HP ของตัวเกิดใหม่ = 30 * (1 + 0.4 * longestRunMinutes)
- ที่ 6 นาที สูตรให้ 295 ตัว / HP 102; ที่ 8 นาที 385 ตัว / HP 126
  เป็นค่าคำนวณจาก config ไม่ใช่ผลทดลองบาลานซ์ จำนวนจริงขึ้นกับการเกิด/ตาย
- GAME-32 ใช้ arena ร่วมกัน และอาจมีคนเข้าในรอบที่กำลังเล่นอยู่
  Map1 ยังมีข้อจำกัดศัตรูเดินผ่านต้นไม้/พีระมิด จึงไม่ควรนับสิ่งเหล่านี้เป็นที่กำบัง

เปรียบเทียบความยาว (เวลาต่อสู้ ไม่รวมการเลือกการ์ด)
ทางเลือก | ข้อดี | สิ่งที่ต้องพิสูจน์
6 นาที   | จบไว เล่นซ้ำและทดลอง build ได้บ่อย | ช่วงสร้าง build/Evolve อาจสั้นเกิน
8 นาที   | มีเวลาสร้าง build แล้วใช้ช่วงท้ายประมาณ 2 นาที | นาที 3–6 อาจกลายเป็นวนรอ
เลือก 8 นาทีเป็นสมมติฐานเริ่มต้น ไม่ใช่การล็อกค่าถาวร
หากช่วงกลางน่าเบื่อ ให้ลอง 6 นาทีด้วยจุดทดสอบเดียวกันก่อนเพิ่มคอนเทนต์จำนวนมาก
การตัดเหลือ 6 นาทีต้องบันทึกด้วยว่าแรงกดดันช่วงท้ายต่ำลงตามสูตรเดิม
จึงเป็นการเทียบประสบการณ์สองเวอร์ชัน ไม่ใช่การทดลองที่แยกผลของเวลาอย่างเดียว

ไทม์ไลน์ 8 นาที (ทุก milestone ด้านเลเวลเป็นเป้าทดลอง ไม่ใช่ของแจกตามเวลา)
ช่วง      | ประสบการณ์ที่ต้องการ | หมุดหมายที่สังเกตได้
0:00–1:00 | เรียนรู้เดินหลบ อาวุธยิงเอง เก็บ gem และเลือกการ์ด | อัปเกรดแรก 20–40 วินาที
1:00–3:00 | เริ่มเลือกแนว build: ตีใกล้/ยิงไกล/วงไฟ | ราว Lv4–6; อธิบายเหตุผลเลือกการ์ดได้
3:00–6:00 | ใช้ build ฝ่าฝูงที่แน่นขึ้น เลือกทางเข้าเก็บ XP | ราว Lv8–10; มีอาวุธหลัก Lv4–5
6:00–7:00 | ใช้พลังที่สร้างมา เตรียมรับช่วงสุดท้าย | รู้ว่าขาดอีกเท่าไรจึงชนะ
7:00–8:00 | จุดพีคเดียว: รอดจากฝูงช่วงท้าย | หลบ/เปลี่ยนเส้นทาง ไม่ใช่ยืนนิ่งรอ
8:00      | หยุดการต่อสู้และสรุปชัยชนะทันที | เข้าใจว่าชนะเพราะอยู่รอดครบเวลา

ต้นแบบแรกใช้การเพิ่มจำนวน/HP ตาม config เดิม เพื่อดูว่ากราฟปัจจุบันทำหน้าที่ได้ไหม
ยังไม่เพิ่ม spike, damage multiplier หรือ wave ใหม่โดยเดาว่าจะสนุกขึ้น
ข้อความช่วงสุดท้ายใน HUD เสนอให้ใช้ “FINAL MINUTE”; เป้าหมายหลัก “SURVIVE 8:00”
ผู้เล่นไม่จำเป็นต้องยืนลานกลางหรือฆ่าศัตรูหมด เพราะเป็นรอบเอาตัวรอดและศัตรูเกิดทดแทน
หากต้องมี climax แบบ elite ให้ใช้ GAME-28 หลังรู้ว่าช่วงท้ายเดิมขาดอะไร

สิ่งที่ผู้เล่นควรรู้ภายในนาทีแรก
1. อาวุธโจมตีเอง หน้าที่เราคือเลือกทางเดินและหลบวงโจมตี
2. gem ใช้เพิ่มเลเวล การเลือกการ์ดทำให้ build เปลี่ยน
3. เป้าหมายคือรอดครบ 8 นาที ไม่ใช่เคลียร์แผนที่หรือฆ่าก๊อบลินทุกตัว
ตรวจด้วยการให้ผู้เล่นอธิบายเองหลังจบนาทีแรก ไม่บอกคำตอบก่อนถาม

กติกาจบรอบที่เสนอสำหรับต้นแบบ solo
- เซิร์ฟเวอร์เป็นผู้ตัดสิน; เวลาที่เพิ่มต้องมาจากช่วงที่ simulation เดินจริง
  หยุดเวลาเป้าหมายระหว่าง pause; แยกเวลาหน้าจอ/เวลาเลือกการ์ดไว้ในการวัด
- ตายก่อนครบเวลา = defeated; รอดครบ 480 วินาที = victory; จบได้ครั้งเดียวต่อ runId
- ใน tick ที่ถึงเส้นชัย ให้ตัดสินความเสียหายของ tick นั้นก่อน แล้วตรวจว่าผู้เล่นยังมีชีวิต
  ถ้าตายใน tick เดียวกันให้ defeated เพื่อไม่ให้ผลขึ้นกับลำดับ callback
- ผู้เล่นต้องอยู่ในขอบ arena; ออกขอบให้หยุดสะสมเวลาชนะและเริ่ม grace 5 วินาที
  หากไม่กลับให้ abandoned; กลับได้จะล้าง grace แต่ไม่ให้เวลาที่อยู่นอก arena คืน
  เป็นกติกาใหม่ที่ต้องทดสอบกับ knockback/ขอบ Map1 ไม่ใช่พฤติกรรมที่มีอยู่แล้ว
- ออกจากเซิร์ฟเวอร์/กลับ lobby ก่อนชนะ = abandoned ไม่มีชัยชนะหรือรางวัลย้อนหลัง
- ตอนจบให้ยกเลิกความเสียหาย/การ์ดค้างสำหรับ run นั้น ก่อนย้ายผู้เล่นออกจาก arena
  ต้องกัน step() สร้าง run ใหม่ทันทีที่ยังยืนอยู่ใน arena ด้วยสถานะ terminal
- Play Again เริ่ม runId ใหม่จากศูนย์; Lobby กลับ camp; ไม่สืบทอด XP/อาวุธ/เวลารอบก่อน
- ใช้หน้าผลเดิม: victory = “VICTORY!”, defeated = “RUN ENDED”, abandoned = “RUN LEFT”
  เก็บ time/kills/level/damage และเพิ่ม outcome; ยังไม่มีเงิน/ปลดล็อก/รางวัลถาวร
  disconnect บันทึก outcome ฝั่งเซิร์ฟเวอร์ได้ แต่ไม่อ้างว่าส่งหน้าผลให้ผู้เล่นที่ออกไปแล้ว

ขอบเขต co-op ที่ต้องให้ GAME-27 ตัดสินก่อนเปิดใช้หลายคน
ต้นแบบ GAME-26 ทดสอบแบบ solo ในสภาพแวดล้อมทดสอบเท่านั้น ยังไม่เปลี่ยน public runs
ต้องเลือกระหว่าง shared encounter clock กับ per-player clock รวมถึง late join,
คนตายแล้วกลับเข้ารอบ, XP ownership, และชัยชนะของคนหนึ่งจบของคนอื่นหรือไม่
ห้ามเพิ่ม victory timer รายคนใน arena ร่วมปัจจุบันโดยอัตโนมัติ เพราะคนเข้าใหม่อาจ
เจอฝูงที่สเกลตามคนเก่า หรือได้ชัยชนะจากเวลาที่เพื่อนใช้เลือกการ์ด
ไม่เสนอเปลี่ยน pause ของ GAME-11 ผ่านงานนี้

ความสัมพันธ์กับงานอื่น
GAME-12/Evolve: ไม่เป็นเงื่อนไขชนะรุ่นแรก อาวุธ 3 แบบปัจจุบันทดสอบวงจรได้
เมื่อ Evolve พร้อม ให้ทดสอบได้ใช้ช่วงนาที 5–6 และเหลือเวลาสนุกกับมัน 2–3 นาที
ถ้าการสุ่มทำให้เข้าไม่ถึง ให้แยกการทดสอบ build ที่กำหนดไว้จากการสุ่มจริง
อย่าเพิ่มอัตรา XP หรือบังคับแจกคู่ Evolve เพื่อซ่อนปัญหาโดยไม่บันทึก
GAME-11/balance: ต้องพิจารณา XP/HP/spawn จากผลเล่นจริงเทียบ milestone เหล่านี้
ผู้ใช้ยกเลิก implementation เดิมแล้ว เอกสารนี้ไม่ได้อนุญาตให้นำกลับมาใช้
GAME-23: มี baseline ฝูง แต่ไม่ได้รับรอง full combat/Map1/mobile และไม่ใช่หลักฐานว่า
385 ตัวพร้อมอาวุธ/ฉากจริงจะลื่นบนอุปกรณ์เป้าหมาย ต้องวัดบนฉากที่คงที่ภายหลัง
GAME-25: เมื่อ run lifecycle รุ่นแรกนิ่ง ให้ทดสอบ 20 restarts + 15-minute soak
รวม victory/defeat/abandon/disconnect; แก้ defect ที่ทำซ้ำได้ก่อนเพิ่มระบบจำนวนมาก
GAME-24: ทำเมื่อวัดว่าการส่งข้อมูลให้ผู้เล่นกระจายตัวเป็นปัญหาจริง
GAME-28/29: ใช้ timeline นี้เป็นกรอบทดลองหลัง GAME-27 ไม่เพิ่ม elite และ objective
พร้อมกันในการทดสอบแรก เพราะจะหาสาเหตุความสนุก/ความยากได้ยาก
GAME-32: ใช้พื้นที่เดิมที่ตกลงไว้; ตรึง map revision ตอนเปรียบเทียบ และบันทึก deaths
จากศัตรูทะลุสิ่งกีดขวางแยกจาก pacing ไม่ตีความว่าต้องลด damage อย่างเดียว

แผนทดลองเล่นหลังทำต้นแบบ (ยังไม่ได้ดำเนินการในงานออกแบบนี้)
เตรียม: บันทึก commit/map revision/device/input, ใช้ solo, ไม่มีการแก้ฉากกลางการทดลอง
ตรวจ timer/outcome/restart ให้ถูกก่อนวัดความสนุก; ปิดต้นแบบเป็นค่าเริ่มต้น
กลุ่มเล็กเริ่มต้น: ผู้เล่นใหม่ 6 คน คนละ 2 รอบ สลับลำดับ 6→8 และ 8→6 อย่างละ 3 คน
ใช้ RNG seeds สองชุดโดยสลับชุดกับระยะเวลา บันทึกการ์ดที่เสนอ/เลือกจริง ไม่บังคับ build
เป็นการทดลองเชิงสำรวจ ไม่ใช่ข้อพิสูจน์ทางสถิติ; เก็บรอบที่ตายก่อนจบด้วย
ถ้าคนส่วนใหญ่ตายก่อน 3 นาที ยังสรุปความยาวที่ชอบไม่ได้ ให้แก้ปัญหาเปิดเกมแล้วทดลองซ้ำ

สิ่งที่เก็บต่อรอบ:
- เวลา combat/wall-clock/เลือกการ์ด, อัปเกรดแรก, เลเวลและ loadout ที่ 1/3/6 นาที
- เวลา/ตำแหน่ง/สาเหตุตาย, outcome, อาการศัตรูทะลุวัตถุ, ช่วงที่ยืนนิ่งปลอดภัย
- คำตอบเป้าหมายเกม, ช่วงน่าเบื่อที่สุด, ความตึงเครียดท้ายรอบ 1–5, อยากเล่นอีกหรือไม่
- FPS จาก foreground บนอุปกรณ์ที่ทดสอบ และ server timing เพื่อแยกอาการหน่วงจากกติกา

เกณฑ์ตัดสินล่วงหน้า (เป้าทดลอง ไม่ใช่ผลที่ผ่านแล้ว):
คำถาม | หลักฐาน/เกณฑ์เบื้องต้น | ถ้าไม่ถึงเป้า
เข้าใจเกมไหม | อย่างน้อย 5/6 อธิบายเดินหลบ+gem+อยู่รอดครบเวลาได้ | ปรับคำแนะนำก่อนเพิ่มระบบ
เริ่มสนุกเร็วไหม | อย่างน้อย 4/6 ได้เลือกการ์ดแรกใน 20–40 วินาที | ตรวจการเก็บ XP/อัตราเกิด แล้วเสนอ balance แยก
มี build ก่อนท้ายไหม | อย่างน้อยสองในสามของคนที่ถึงนาที 6 มีอาวุธหลัก Lv4–5 | ดูตัวเลือกและ XP ก่อนเพิ่มศัตรู
ช่วงกลางยืดไหม | ไม่เกิน 2/6 ระบุช่วงนาที 3–6 ว่าแค่รอ | ลอง 6 นาที; อย่าเพิ่ม objective ทันที
ท้ายรอบมี climax ไหม | คนที่ถึงท้ายให้ความตึงเครียด 3–4/5 และอธิบายการหลบ/เปลี่ยนทางได้ | ทดลอง pacing หรือ elite ทีละอย่าง
รู้ว่าจบแล้วไหม | ทุกคนแยก victory/defeat ได้จากหน้าผล | แก้ข้อความ/outcome ก่อนทดสอบต่อ
เลือก 8 หรือ 6 | อย่างน้อย 4/6 ชอบ 8 และผ่านเกณฑ์เข้าใจ/ช่วงกลาง | ถ้าเสมอเลือก 6 สำหรับต้นแบบถัดไป แล้วทดสอบใหม่
หากผู้เล่นถึงนาที 6 น้อยกว่า 4 คน ให้รายงาน milestone/ช่วงท้ายว่า evidence ไม่พอ

